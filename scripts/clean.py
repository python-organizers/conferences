def fold(value):
    '''Lowercase ASCII form, so "Kraków" and "Krakow" compare equal.'''
    value = unicodedata.normalize('NFKD', value)
    value = value.encode('ascii', 'ignore').decode()
    return re.sub(r'[^a-z0-9]', '', value.lower())


def is_similar(a, b, min_ratio):
    return SequenceMatcher(None, a, b).ratio() >= min_ratio


def find_city_misspellings(locations, min_ratio=0.85):
    '''Map row index -> (city, likely spelling), within each country.'''
    cities = pd.DataFrame({
        'city': locations.map(lambda v: v.split(',')[0].strip()),
        'country': locations.map(country_from_location)})
    cities = cities[(cities['city'] != '') & (cities['country'] != '')]
    counts = cities.value_counts()
    corrections = {}
    for (city, country), count in counts.items():
        rivals = [
            (other_count, len(other), other)
            for (other, other_country), other_count in counts.items()
            if other_country == country and other != city
            and (other_count, len(other)) > (count, len(city))
            and is_similar(fold(city), fold(other), min_ratio)]
        if rivals:
            corrections[city, country] = max(rivals)[2]
    return {
        index: (row.city, better)
        for index, row in cities.iterrows()
        if (better := corrections.get((row.city, row.country)))}


def find_inconsistencies(raw, max_event_days=14):
    '''Check the raw CSV; row numbers match the file (header is row 1).'''
    issues = []

    def add(index, column, severity, issue, value='', detail=''):
        issues.append({
            'row': index + 2, 'column': column, 'severity': severity,
            'issue': issue, 'value': value, 'detail': detail})

    subjects, subject_notes = harmonize_subjects(
        raw['Subject'].map(clean_text).map(clean_subject))
    first_seen = {}
    for index, row in raw.iterrows():
        if not any(row):
            add(index, '', 'error', 'blank row')
            continue
        if (key := tuple(row)) in first_seen:
            add(index, '', 'warning', 'exact duplicate',
                detail=f'same as row {first_seen[key] + 2}')
            continue
        first_seen[key] = index

        for column, value in row.items():
            if value != value.strip() or '  ' in value:
                add(index, column, 'warning', 'extra whitespace', value)

        # Dates
        dates = {}
        for column in DATE_COLUMNS:
            if not (value := row[column]):
                continue
            parsed = pd.to_datetime(value, errors='coerce')
            if not re.fullmatch(r'\d{4}-\d{2}-\d{2}', value) or \
                    pd.isna(parsed):
                add(index, column, 'error',
                    'not a valid YYYY-MM-DD date', value)
            else:
                dates[column] = parsed
        start, end = dates.get('Start Date'), dates.get('End Date')
        if not row['Start Date']:
            add(index, 'Start Date', 'warning', 'missing start date')
        elif not row['End Date']:
            add(index, 'End Date', 'warning', 'missing end date')
        if start is not None and end is not None:
            if end < start:
                fixed = fix_end_year(row['Start Date'], row['End Date'])
                if fixed >= row['Start Date']:
                    add(index, 'End Date', 'info', END_YEAR_ISSUE,
                        row['End Date'], fixed)
                else:
                    add(index, 'End Date', 'error',
                        'end date before start date', row['End Date'])
            elif (days := (end - start).days) > max_event_days:
                add(index, 'End Date', 'warning',
                    f'event longer than {max_event_days} days',
                    row['End Date'], f'{days} days')
        for column in ('Tutorial Deadline', 'Talk Deadline'):
            deadline = dates.get(column)
            if start is not None and deadline is not None and \
                    deadline > start:
                add(index, column, 'error',
                    'deadline after start date', row[column])
        year = YEAR.search(row['Subject'])
        if year and row['Start Date'] and \
                year[0] != row['Start Date'][:4]:
            add(index, 'Subject', 'error',
                'year in name does not match start date',
                row['Subject'], row['Start Date'])

        # Subject
        if not row['Subject']:
            add(index, 'Subject', 'error', 'missing name')
        status = re.search(
            r'cancel+ed|postponed', row['Subject'], re.IGNORECASE)
        if status:
            add(index, 'Subject', 'info', 'status stored in name',
                row['Subject'], status[0])
        if TRAILING_NUMBER.search(strip_words(clean_text(row['Subject']))):
            add(index, 'Subject', 'info', NUMBER_ISSUE, row['Subject'])
        if YEAR.search(row['Subject']) or SHORT_YEAR.search(row['Subject']):
            add(index, 'Subject', 'info', 'year removed from name',
                row['Subject'])
        for word, pattern in (('Online', ONLINE_WORD),
                              ('Worldwide', WORLDWIDE)):
            if pattern.search(row['Subject']):
                add(index, 'Subject', 'info',
                    f'"{word}" removed from name', row['Subject'])
        if is_excluded(row['Subject']):
            add(index, 'Subject', 'info', 'row excluded', row['Subject'])
        bare = remove_words(clean_text(row['Subject']))
        for name, preferred in [*NAME_ALIASES.items(), *FULL_NAMES.items()]:
            if whole(name).search(bare):
                add(index, 'Subject', 'info', NAME_ISSUE, row['Subject'],
                    f'{name} -> {preferred}')
        if APAC.search(row['Subject']):
            add(index, 'Subject', 'info', APAC_ISSUE, row['Subject'])
        for issue, detail in subject_notes.get(index, []):
            add(index, 'Subject', 'info', issue, row['Subject'], detail)


        # URLs
        if not row['Website URL']:
            add(index, 'Website URL', 'warning', 'missing website URL')
        for column in URL_COLUMNS:
            if not (value := row[column].strip()):
                continue
            if re.search('[\u201c\u201d"\']', value):
                add(index, column, 'error', 'quotes in URL', value)
            elif not re.match(r'https?://|mailto:', value):
                add(index, column, 'error',
                    'URL missing http(s)://', value)
            elif value.startswith('http://'):
                add(index, column, 'info', 'http instead of https', value)
            path = urlsplit(value.strip('\u201c\u201d')).path
            if value.endswith('/') and path == '/':
                add(index, column, 'info', 'trailing slash', value)

        # Location and country
        location = clean_text(row['Location'])
        if not location:
            add(index, 'Location', 'warning', 'missing location')
        elif ONLINE.match(location) and location != 'Online':
            add(index, 'Location', 'warning',
                'online not spelled "Online"', location)
        elif location != 'Online' and \
                re.search(r'online', location, re.IGNORECASE):
            add(index, 'Location', 'info',
                'hybrid event mixed into location', location)
        if UNITED_STATES.search(location) or US.search(location):
            add(index, 'Location', 'info', USA_ISSUE, location)
        if UK.search(location):
            add(index, 'Location', 'info', UK_ISSUE, location)
        for name, preferred in LOCATION_ALIASES.items():
            if match := location_pattern(name).search(location):
                add(index, 'Location', 'info', LOCATION_ISSUE, location,
                    f'{match[0]} -> {preferred}')
        if codes := [m[0] for m in POSTAL_CODE.finditer(location)]:
            add(index, 'Location', 'info', POSTAL_ISSUE, location,
                ', '.join(codes))
        country = SERIES_COUNTRY.get(subjects[index])
        if country and country not in location:
            add(index, 'Location', 'info', SERIES_COUNTRY_ISSUE, location,
                country)
        if re.search(r'\d{3,}', location):
            add(index, 'Location', 'warning',
                'looks like a street address, belongs in Venue?',
                location)
        if re.search(r'rotating|^(europe|africa|asia)$', location,
                     re.IGNORECASE):
            add(index, 'Location', 'warning',
                'placeholder location', location)
        cleaned = strip_online(clean_location(location))
        last = cleaned.split(',')[-1].strip()
        if cleaned not in ('', 'Online') and not is_country(last):
            add(index, 'Location', 'warning',
                'last part is not a country name', location, last)
        derived = country_from_location(clean_location(location))
        if not row['Country'] and derived:
            add(index, 'Country', 'info',
                'missing, filled from Location', '', derived)
        elif row['Country'] and derived and row['Country'] != derived:
            add(index, 'Country', 'error',
                'does not match Location', row['Country'], derived)

    # Country spelling variants, e.g. USA / United States / US
    locations = raw['Location'].map(clean_location).map(strip_online)
    last = locations.map(lambda v: v.split(',')[-1].strip())
    groups = pd.DataFrame({'value': last, 'key': last.map(to_alpha3)})
    groups = groups[(groups['key'] != '') & (groups['value'] != '')]
    for _, group in groups.groupby('key'):
        if (spellings := group['value'].value_counts()).size > 1:
            preferred = spellings.index[0]
            for index in group.index[group['value'] != preferred]:
                add(index, 'Location', 'warning',
                    'country spelled differently elsewhere',
                    raw.at[index, 'Location'],
                    f'most common: {preferred}')

    # City variants and near misses, e.g. Kraków / Krakow, Hydrabad
    for index, (city, better) in find_city_misspellings(locations).items():
        add(index, 'Location', 'warning',
            'city spelled differently elsewhere',
            raw.at[index, 'Location'], f'{city} -> {better}')

    return pd.DataFrame(issues)


