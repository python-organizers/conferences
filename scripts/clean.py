def describe_issues(issues, row):
    '''"error [End Date]: end date before start date", one per line.'''
    notes = []
    for issue in issues[issues['row'] == row].itertuples():
        note = f'{issue.severity}'
        note += f' [{issue.column}]: ' if issue.column else ': '
        note += issue.issue
        if issue.detail:
            note += f' ({issue.detail})'
        if issue.issue in FIXED_ISSUES:
            note += ' [fixed]'
        notes.append(note)
    return '\n'.join(notes)


def drop_same_events(df, max_days=7):
    '''Remove rows that are the same event as another row, keeping the
    one with the most columns filled (the earliest on a tie). Two rows
    are the same event if either
    - their Subjects match ignoring case, spaces and punctuation
      ("Piter Py" = "PiterPy") and both dates are the same
    - or their Subjects match exactly, their Start Dates are within
      max_days of each other, and so are their End Dates (or one is
      blank)
    Return the kept rows and a map of kept index -> removed indexes.'''
    filled = (df[COLUMNS] != '').sum(axis=1)
    start = pd.to_datetime(df['Start Date'], errors='coerce')
    end = pd.to_datetime(df['End Date'], errors='coerce')

    def gap(dates, i, j):
        days = abs((dates[i] - dates[j]).days)
        return None if pd.isna(days) else days

    def is_same(i, j):
        start_gap, end_gap = gap(start, i, j), gap(end, i, j)
        if start_gap is None:
            return False
        if start_gap == 0 and df.at[i, 'End Date'] == df.at[j, 'End Date']:
            return True
        return df.at[i, 'Subject'] == df.at[j, 'Subject'] and \
            start_gap <= max_days and \
            (end_gap is None or end_gap <= max_days)

    pairs = []
    dated = df[df['Start Date'] != '']
    for _, group in dated.groupby(dated['Subject'].map(fold)):
        rows = list(group.index)
        pairs += [
            (i, j) for n, i in enumerate(rows) for j in rows[n + 1:]
            if is_same(i, j)]
    same = {}
    for rows in group_pairs(pairs):
        best = max(rows, key=lambda i: (filled[i], -i))
        same[best] = sorted(rows - {best})
    dropped = [i for others in same.values() for i in others]
    return df.drop(index=dropped), same


def merge_cancelled(df):
    '''Remove each "(cancelled)" row that has a row in the same series
    with the same Start Date, and add "(cancelled)" to that row instead.
    Return the kept rows and a map of kept index -> notes.'''
    df = df.copy()
    cancelled = df['Subject'].str.contains('(cancelled)', regex=False)
    keys = df['Subject'].map(base_name)
    notes, dropped = {}, []
    for i in df.index[cancelled]:
        matches = df.index[
            ~cancelled & (keys == keys[i]) & (df['Start Date'] != '') &
            (df['Start Date'] == df.at[i, 'Start Date'])]
        if matches.empty:
            continue
        j = matches[0]
        if '(cancelled)' not in df.at[j, 'Subject']:
            df.at[j, 'Subject'] += ' (cancelled)'
        notes.setdefault(j, []).append(
            f'removed cancelled row {i + 2} and marked this row cancelled')
        dropped.append(i)
    return df.drop(index=dropped), notes


def drop_placeholders(df):
    '''Remove rows with a "rotating" Location, or with no Start Date,
    when another row has the same Subject (with a Start Date, for rows
    without one). Return the kept rows and a map of kept index -> notes.'''
    rotating = df['Location'].str.contains('rotating', case=False)
    undated = df['Start Date'] == ''
    notes, dropped = {}, []
    for i in df.index[rotating | undated]:
        others = df.index[
            (df['Subject'] == df.at[i, 'Subject']) & (df.index != i) &
            ~df.index.isin(dropped)]
        if undated[i]:
            others = others[~undated[others]]
        if others.empty:
            continue
        # Attach the note to a row that will stay, if there is one
        if not (real := others[~(rotating | undated)[others]]).empty:
            others = real
        reason = 'rotating location' if rotating[i] else 'no start date'
        notes.setdefault(others[0], []).append(
            f'removed placeholder row {i + 2} ({reason})')
        dropped.append(i)
    return df.drop(index=dropped), notes


def describe_duplicates(
        raw, normalized, removed, same, extra, duplicates, index):
    '''Removed and possible duplicates of one kept row.'''
    notes = [*extra.get(index, [])]
    for other in same.get(index, []):
        note = f'removed as the same event: row {other + 2}'
        differences = describe_differences(
            normalized.loc[index], normalized.loc[other])
        labels = [
            f"named {normalized.at[other, 'Subject']}"
            if column == 'Subject' else label
            for column, label, _ in differences]
        if labels:
            note += f" ({', '.join(labels)})"
        if twins := removed.get(other):
            note += f', which replaced {join_rows([i + 2 for i in twins])}'
        notes.append(note)
    twins = removed.get(index, [])
    exact = [i + 2 for i in twins if raw.loc[i].equals(raw.loc[index])]
    other = [i + 2 for i in twins if i + 2 not in exact]
    if exact:
        notes.append(f'removed exact duplicates: {join_rows(exact)}')
    if other:
        notes.append(
            f'removed after normalizing: {join_rows(other)}')
    if duplicates.empty:
        return '\n'.join(notes)
    for match in duplicates[duplicates['row'] == index + 2].itertuples():
        group = duplicates[duplicates['group'] == match.group]
        others = [r for r in group['row'] if r != index + 2]
        note = f'possible duplicate of {join_rows(others)}'
        if match.differences:
            note += f' ({match.differences})'
        notes.append(note)
    return '\n'.join(notes)


def join_rows(rows):
    '''[5] -> "row 5", [5, 7] -> "rows 5, 7".'''
    label = 'row' if len(rows) == 1 else 'rows'
    return f"{label} {', '.join(str(r) for r in rows)}"


def order_rows(df, duplicates):
    '''Sort by name and date, keeping potential duplicates together
    at the position of the group's first member.'''
    df = df.sort_values(
        ['Subject', 'Start Date'], key=lambda s: s.str.lower())
    position = pd.Series(range(len(df)), index=df.index + 2)
    group_position = position.copy()
    if not duplicates.empty:
        groups = duplicates.set_index('row')['group']
        first = position[groups.index].groupby(groups.values).min()
        group_position[groups.index] = groups.map(first).values
    order = pd.DataFrame({
        'group': group_position.values, 'position': position.values})
    return df.iloc[order.sort_values(['group', 'position']).index]


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument(
        'csv', type=Path, nargs='?',
        default=DRAFTS_FOLDER / 'conferences.csv')
    args = parser.parse_args()
    DRAFTS_FOLDER.mkdir(parents=True, exist_ok=True)

    raw = pd.read_csv(args.csv, dtype=str, keep_default_na=False)[COLUMNS]
    print(f'{len(raw)} rows read')

    # 1. Exact duplicates, then ones that differed only by whitespace,
    # quotes or trailing slashes; remember which kept row each replaced
    blank = ~(raw != '').any(axis=1)
    excluded = raw['Subject'].map(is_excluded)
    raw_kept = raw[~blank & ~excluded]
    normalized = normalize(raw_kept)
    kept, removed = {}, {}
    for index, key in zip(normalized.index, normalized.itertuples(
            index=False, name=None)):
        if (first := kept.setdefault(key, index)) != index:
            removed.setdefault(first, []).append(index)
    df = normalized.loc[list(kept.values())]
    exact_count = raw_kept.duplicated().sum()
    print(f'{blank.sum()} blank rows removed')
    print(f'{excluded.sum()} excluded rows removed')
    print(f'{exact_count} exact duplicates removed')
    print(f'{len(normalized) - len(df) - exact_count} more duplicates '
          'removed after normalizing')

    # 2. Same event: keep the row with more filled in
    df, same = drop_same_events(df)
    print(f'{sum(map(len, same.values()))} rows removed as the same '
          'event')

    # 3. Cancelled rows and placeholders
    df, cancelled = merge_cancelled(df)
    print(f'{sum(map(len, cancelled.values()))} cancelled rows merged')
    df, placeholders = drop_placeholders(df)
    print(f'{sum(map(len, placeholders.values()))} placeholder rows '
          'removed')
    extra = {}
    for notes in (cancelled, placeholders):
        for index, lines in notes.items():
            extra.setdefault(index, []).extend(lines)

    # 4. Potential duplicates
    duplicates, duplicate_issues = find_potential_duplicates(df)
    duplicates.to_csv(
        DRAFTS_FOLDER / 'potential_duplicates.csv', index=False)
    print(f"{duplicates['group'].nunique()} potential duplicates flagged")

    # 5. Inconsistencies
    row_issues = find_inconsistencies(raw)
    issues = pd.concat([row_issues, duplicate_issues], ignore_index=True)
    issues = issues.sort_values(['row', 'column'], kind='stable')
    issues.to_csv(DRAFTS_FOLDER / 'inconsistencies.csv', index=False)
    print(f'{len(issues)} inconsistencies found:')
    counts = issues.groupby(['severity', 'issue']).size()
    print(counts.sort_values(ascending=False).to_string())

    # 6. Comment columns, so each row can be reviewed on its own
    df = df.assign(
        Row=df.index + 2,
        Issues=[describe_issues(row_issues, i + 2) for i in df.index],
        Duplicates=[
            describe_duplicates(
                raw, normalized, removed, same, extra, duplicates, i)
            for i in df.index])
    df = order_rows(df, duplicates)
    df = df[['Row', *COLUMNS, 'Issues', 'Duplicates']]
    df.to_csv(DRAFTS_FOLDER / 'conferences_clean.csv', index=False)
    write_ods(for_review(df), DRAFTS_FOLDER / 'conferences_clean.ods')
    print(f'{len(df)} rows written to {DRAFTS_FOLDER.resolve()}')


if __name__ == '__main__':
    main()
