# ---------- cleaning ----------

def clean_text(value):
    value = unicodedata.normalize('NFC', value or '')
    value = value.replace('\u00a0', ' ').strip()
    return re.sub(r'\s+', ' ', value)


def tidy(value):
    '''Clean up the gaps left after removing a word from a name.'''
    value = re.sub(r'\([\s-]*\)', '', value)  # "(2020)" left "()"
    value = re.sub(r'\(\s*-?\s*', '(', value)  # "(Online-Worldwide)"
    value = re.sub(r'\s+([:,.)])', r'\1', value)
    return clean_text(value).strip(' -:,')


def whole(name, flags=0):
    '''Pattern matching name as a whole word, even if it starts or ends
    with punctuation, like "PyConZA (South Africa)".'''
    return re.compile(rf'(?<!\w){re.escape(name)}(?!\w)', flags)


def is_excluded(subject):
    return any(
        whole(name, re.IGNORECASE).search(subject) for name in EXCLUDED)


def remove_words(value):
    '''Drop the year (including "'20"), "Online" and "Worldwide":
    "FOSDEM 2020: Python Dev Room" -> "FOSDEM: Python Dev Room"'''
    for pattern in (YEAR, SHORT_YEAR, ONLINE_WORD, WORLDWIDE):
        value = pattern.sub('', value)
    return tidy(value)


def strip_words(value):
    '''remove_words, then apply NAME_ALIASES and FULL_NAMES and spell
    out "APAC": "PyCon APAC 2023" -> "PyCon Asia Pacific"'''
    value = remove_words(value)
    for name, preferred in NAME_ALIASES.items():
        value = whole(name).sub(preferred, value)
    for name, full_name in FULL_NAMES.items():
        if whole(name).search(value):
            value = full_name
    return tidy(APAC.sub('Asia Pacific', value))


def clean_subject(value):
    '''strip_words, then drop any number at the end: "PyCon IT 9" ->
    "PyCon IT", "PiterPy #5" -> "PiterPy", "csv,conf,v8" -> "csv,conf"'''
    return tidy(TRAILING_NUMBER.sub('', strip_words(value)))


def harmonize_conf(subjects):
    '''Within each series, add or remove the word "Conf" to match most
    of its rows; leave ties alone. Return (subjects, notes), where notes
    maps row index -> explanation for each changed row.'''
    subjects = subjects.copy()
    notes = {}
    has_conf = subjects.map(lambda v: bool(CONF.search(v)))
    for key, group in subjects.groupby(subjects.map(base_name)):
        with_conf = has_conf[group.index]
        count, total = with_conf.sum(), len(group)
        if not key or count in (0, total) or count * 2 == total:
            continue
        detail = f'{count} of {total} rows in this series have "Conf"'
        if count * 2 < total:
            for index in group.index[with_conf]:
                subjects[index] = tidy(CONF.sub('', subjects[index]))
                notes[index] = ('"Conf" removed from name', detail)
            continue
        # Insert "Conf" where the most common spelling has it
        target = group[with_conf].value_counts().index[0]
        prefix = tidy(CONF.sub('', target))
        for index in group.index[~with_conf]:
            if (value := subjects[index]).startswith(prefix):
                subjects[index] = target + value[len(prefix):]
                notes[index] = ('"Conf" added to name', detail)
    return subjects, notes


def harmonize_spelling(subjects):
    '''Within each series of names that match ignoring case, spaces and
    punctuation ("Piter Py", "PiterPy"), use the preferred name from
    NAME_ALIASES if there is one, else the most common spelling; leave
    ties alone. Return (subjects, notes) like harmonize_conf.'''
    subjects = subjects.copy()
    notes = {}
    preferred = {
        fold(name): name
        for name in [*NAME_ALIASES.values(), *FULL_NAMES.values()]}
    for key, group in subjects.groupby(subjects.map(fold)):
        spellings = group.value_counts()
        if not key or len(spellings) < 2:
            continue
        if target := preferred.get(key):
            detail = f'{target}: preferred name'
        elif spellings.iloc[0] == spellings.iloc[1]:
            continue
        else:
            target, count = spellings.index[0], spellings.iloc[0]
            detail = f'{target}: {count} of {len(group)} rows in this series'
        for index in group.index[group != target]:
            notes[index] = (RESPELLED_ISSUE, detail)
            subjects[index] = target
    return subjects, notes


def harmonize_subjects(subjects):
    '''Apply harmonize_conf, then harmonize_spelling. Return (subjects,
    notes), where notes maps row index -> list of (issue, detail).'''
    subjects, conf_notes = harmonize_conf(subjects)
    subjects, spelling_notes = harmonize_spelling(subjects)
    notes = {}
    for index in [*conf_notes, *spelling_notes]:
        notes[index] = [
            n[index] for n in (conf_notes, spelling_notes) if index in n]
    return subjects, notes


def clean_url(value):
    value = clean_text(value).strip('\u201c\u201d"\' ')
    value = re.sub(r'^http://', 'https://', value, flags=re.IGNORECASE)
    if value and not re.match(r'https://|mailto:', value, re.IGNORECASE):
        value = 'https://' + value
    return value.rstrip('/')


def location_pattern(name):
    return name if isinstance(name, re.Pattern) else whole(name)


def rename_places(value):
    for name, preferred in LOCATION_ALIASES.items():
        value = location_pattern(name).sub(preferred, value)
    return value


def remove_postal_codes(value):
    value = POSTAL_CODE.sub('', value)
    value = re.sub(r'\s*,(\s*,)+', ',', value)  # "27,,51105 Köln"
    value = re.sub(r'\s*,\s*', ', ', value)
    return clean_text(value).strip(' ,')


def clean_location(value):
    '''Rename places, remove postal codes and spell countries
    consistently. Renaming runs before and after the USA and UK
    changes, so it sees both spellings.'''
    value = remove_postal_codes(rename_places(clean_text(value)))
    value = US.sub('USA', UNITED_STATES.sub('USA', value))
    value = rename_places(UK.sub('United Kingdom', value))
    return 'Online' if ONLINE.match(value) else value


def to_alpha3(value):
    if not (value := clean_text(value)):
        return ''
    if alias := COUNTRY_ALIASES.get(value.lower()):
        return alias
    try:
        return pycountry.countries.lookup(value).alpha_3
    except LookupError:
        try:
            return pycountry.countries.search_fuzzy(value)[0].alpha_3
        except LookupError:
            return ''


def is_country(value):
    '''True for a country name or code, e.g. "Brazil", "USA", "UK";
    two-letter codes only if they are in COUNTRY_ALIASES, since "CA"
    is more likely California than Canada.'''
    if value.lower() in COUNTRY_ALIASES:
        return True
    if len(value) <= 2:
        return False
    try:
        pycountry.countries.lookup(value)
    except LookupError:
        return False
    return True


def country_name(alpha3):
    country = pycountry.countries.get(alpha_3=alpha3)
    return country.name if country else ''


def strip_online(location):
    '''"Basel, Switzerland & Online" -> "Basel, Switzerland".'''
    return re.sub(
        r',?\s*(&|and)\s*online.*$', '', location, flags=re.IGNORECASE)


def country_from_location(location):
    if not location or location == 'Online':
        return ''
    last = strip_online(location).split(',')[-1].strip()
    if last.isupper() and len(last) == 2 and \
            last.lower() not in COUNTRY_ALIASES:
        return ''  # 'CA' is more likely California than Canada
    return to_alpha3(last)


def fix_end_year(start, end):
    '''If end is before start, give it the start's year; return end as
    is when either date is not YYYY-MM-DD or the fix is impossible.'''
    if not (re.fullmatch(r'\d{4}-\d{2}-\d{2}', start or '') and
            re.fullmatch(r'\d{4}-\d{2}-\d{2}', end or '')) or end >= start:
        return end
    fixed = start[:4] + end[4:]
    return fixed if pd.notna(pd.to_datetime(fixed, errors='coerce')) \
        else end


def normalize(df):
    df = df.copy()
    for column in COLUMNS:
        df[column] = df[column].map(clean_text)
    for column in URL_COLUMNS:
        df[column] = df[column].map(clean_url)
    df['Subject'], _ = harmonize_subjects(
        df['Subject'].map(clean_subject))
    df['Location'] = df['Location'].map(clean_location)
    df['End Date'] = [
        fix_end_year(a, b) for a, b in zip(df['Start Date'], df['End Date'])]
    for series, country in SERIES_COUNTRY.items():
        rows = (df['Subject'] == series) & \
            ~df['Location'].str.contains(country, regex=False)
        df.loc[rows, 'Location'] = df.loc[rows, 'Location'].map(
            lambda v: f'{v}, {country}' if v else country)
    missing = df['Country'] == ''
    df.loc[missing, 'Country'] = df.loc[missing, 'Location'].map(
        country_from_location)
    return df


