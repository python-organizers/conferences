def write_ods(
        df, path, wide_columns=('Issues', 'Duplicates'),
        tight_columns=('Row', 'Start Date', 'End Date')):
    '''Save df as an .ods spreadsheet with top-aligned, wrapped text in
    every cell and one line per newline. Columns are 1" wide, except
    the wide_columns, which are 3" wide, and the tight_columns, which
    are just wide enough for their contents.'''
    doc = OpenDocumentSpreadsheet()
    doc.fontfacedecls.addElement(FontFace(
        name='Arial', fontfamily='Arial', fontfamilygeneric='swiss'))

    def add_style(name, family, *properties):
        style = Style(name=name, family=family)
        for element in properties:
            style.addElement(element)
        doc.automaticstyles.addElement(style)
        return style

    narrow = add_style(
        'narrow', 'table-column', TableColumnProperties(columnwidth='1in'))
    wide = add_style(
        'wide', 'table-column', TableColumnProperties(columnwidth='3in'))
    wrap = add_style(
        'wrap', 'table-cell', TextProperties(fontname='Arial'),
        TableCellProperties(wrapoption='wrap', verticalalign='top'))

    def column_style(column):
        if column in wide_columns:
            return wide
        if column not in tight_columns:
            return narrow
        # About 0.08" per digit in 10pt Arial, plus cell padding;
        # the header may wrap, but not in the middle of a word
        values = df[column].astype(str)
        characters = max(
            values.str.len().max(), *map(len, column.split()))
        return add_style(
            f"tight-{column.replace(' ', '-')}", 'table-column',
            TableColumnProperties(
                columnwidth=f'{0.08 * characters + 0.1:.2f}in'))

    table = Table(name=path.stem)
    for column in df.columns:
        table.addElement(TableColumn(stylename=column_style(column)))
    for values in [list(df.columns), *df.itertuples(index=False)]:
        row = TableRow()
        for column, value in zip(df.columns, values):
            if (value := str(value)).isdigit():
                cell = TableCell(
                    valuetype='float', value=value, stylename=wrap)
            else:
                cell = TableCell(valuetype='string', stylename=wrap)
            for line in value.splitlines():
                cell.addElement(P(text=line))
            row.addElement(cell)
        table.addElement(row)
    doc.spreadsheet.addElement(table)
    doc.save(str(path))


def for_review(df):
    '''Copy of df for the .ods file, leaving out info-level issues,
    the ODS_HIDDEN_ISSUES and the ODS_HIDDEN_DUPLICATES notes.'''
    def keep_issue(line):
        return not line.startswith('info') and \
            not any(issue in line for issue in ODS_HIDDEN_ISSUES)

    def keep_duplicate(line):
        return not line.startswith(ODS_HIDDEN_DUPLICATES)

    df = df.copy()
    for column, keep in (('Issues', keep_issue),
                         ('Duplicates', keep_duplicate)):
        if column in df:
            df[column] = df[column].map(lambda v: '\n'.join(
                line for line in v.split('\n') if keep(line)))
    return df


