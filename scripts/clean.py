def base_name(subject):
    '''Series name without year, status or "Conf":
    "AfroPython Conf 2025 (canceled)" -> "afropython".'''
    subject = re.sub(
        r'\((cancel+ed|postponed|online|virtual)\)', '', subject,
        flags=re.IGNORECASE)
    return fold(CONF.sub('', YEAR.sub('', subject)))


def describe_gap(a, b):
    '''"1 day", "2-7 days" or "over a week"; None if a date is invalid.'''
    days = pd.to_datetime(b, errors='coerce') - \
        pd.to_datetime(a, errors='coerce')
    if pd.isna(days):
        return None
    if (gap := abs(days.days)) == 1:
        return '1 day'
    return '2-7 days' if gap <= 7 else 'over a week'


def describe_differences(a, b):
    '''List (column, label, detail) for each column where a and b differ.'''
    notes = []
    for column in COLUMNS:
        if (x := a[column]) == (y := b[column]):
            continue
        if not x or not y:
            label = f'{column} missing in one'
        elif column == 'Subject' and base_name(x) == base_name(y):
            label = 'name spelled differently'
        elif column in DATE_COLUMNS and (gap := describe_gap(x, y)):
            label = f'{column} differs by {gap}'
        elif column == 'Location' and \
                fold(x.split(',')[0]) == fold(y.split(',')[0]) and \
                country_from_location(x) == country_from_location(y):
            label = 'Location formatted differently'
        else:
            label = f'{column} differs'
        notes.append((column, label, f'{x or "(blank)"} | {y or "(blank)"}'))
    return notes


def group_pairs(pairs):
    '''Merge overlapping pairs into groups: (A, B), (B, C) -> {A, B, C}.'''
    parent = {}

    def root(i):
        while (p := parent.get(i, i)) != i:
            i = p
        return i

    for i, j in pairs:
        parent[root(j)] = root(i)
    groups = {}
    for i, j in pairs:
        groups.setdefault(root(i), set()).update((i, j))
    return list(groups.values())


def find_potential_duplicates(df, max_days=3, min_ratio=0.85):
    '''Group rows starting within max_days of each other whose names
    match closely, or loosely if they are in the same city.'''
    rows = df.assign(
        series=df['Subject'].map(base_name),
        start=pd.to_datetime(df['Start Date'], errors='coerce'),
        city=df['Location'].map(lambda v: fold(v.split(',')[0])))
    rows = rows.dropna(subset=['start'])
    separate = [{base_name(a), base_name(b)} for a, b in SEPARATE_SERIES]
    pairs = []
    for _, group in rows.groupby(rows['start'].dt.year):
        records = list(group.itertuples())
        for i, a in enumerate(records):
            for b in records[i + 1:]:
                if abs((a.start - b.start).days) > max_days:
                    continue
                if {a.series, b.series} in separate:
                    continue
                ratio = SequenceMatcher(None, a.series, b.series).ratio()
                same_city = a.city and a.city == b.city
                if ratio >= min_ratio or (same_city and ratio >= 0.5):
                    pairs.append((a.Index, b.Index, round(ratio, 2)))

    groups = [
        {'rows': rows, 'ratio': min(
            ratio for i, _, ratio in pairs if i in rows)}
        for rows in group_pairs([(i, j) for i, j, _ in pairs])]

    report, issues = [], []
    for group_id, group in enumerate(groups, 1):
        first, *others = sorted(group['rows'])
        for index in [first, *others]:
            notes = describe_differences(df.loc[first], df.loc[index])
            report.append({
                'group': group_id, 'row': index + 2,
                'similarity': group['ratio'],
                'differences': ', '.join(label for _, label, _ in notes),
                **df.loc[index, COLUMNS].to_dict()})
            issues += [{
                'row': index + 2, 'column': column, 'severity': 'warning',
                'issue': f'potential duplicate: {label}', 'value': '',
                'detail': f'vs row {first + 2}: {detail}',
            } for column, label, detail in notes]
    return pd.DataFrame(report), pd.DataFrame(issues)


